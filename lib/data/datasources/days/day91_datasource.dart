⚠️ ORIGEN - "CUT TO THE CHASE":
Viene del cine antiguo. Las películas tenían mucha conversación aburrida antes de las escenas de persecución (chase scenes) emocionantes. Los editores decían "cut to the chase" = corta directo a la escena de acción.

Ahora significa: ir directo al punto importante.

💡 "BEAT AROUND THE BUSH" vs "CUT TO THE CHASE":
Son OPUESTOS:
- Beat around the bush = evitar el tema, ser indirecto ❌
- Cut to the chase = ir al grano, ser directo ✅

Ejemplo:
"Stop beating around the bush and cut to the chase!"
(¡Deja de andar por las ramas y ve al grano!)

🎯 "GET COLD FEET" - ORIGEN:
Viene de los soldados que tenían los pies congelados y no podían luchar.
Ahora = tener miedo de hacer algo en el último momento.

Muy común antes de:
- Bodas: "He got cold feet before the wedding"
- Presentaciones: "Don't get cold feet now!"
- Decisiones importantes: "She's getting cold feet"

⚠️ "HIT THE SACK" vs "HIT THE HAY":
Mismo significado = irse a dormir
Origen antiguo: los colchones eran sacos (sacks) rellenos de heno (hay)
Ahora son frases casuales para "ir a la cama"

💡 USO EN NEGOCIOS:
Estos idioms son COMUNES en contextos profesionales:

