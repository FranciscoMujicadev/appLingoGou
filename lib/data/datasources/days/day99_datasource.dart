- Situaciones complejas 🧩

💡 "THROUGH THICK AND THIN" - ORIGEN:
"Thick" = bosque denso (difícil de atravesar)
"Thin" = bosque claro (fácil de atravesar)

Atravesar bosques densos Y claros = estar juntos en lo difícil Y lo fácil.

Ahora = lealtad inquebrantable en todas las circunstancias.

