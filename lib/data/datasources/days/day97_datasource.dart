Variaciones comunes:

1. "To make a long story short..." (formal)
2. "Long story short..." (casual)
3. "To cut a long story short..." (británico)

Todas significan: "Resumiendo..."

Se usa cuando:
- Estás contando algo largo y quieres resumir
- Alguien pregunta "What happened?" y quieres ir al punto
- Tienes poco tiempo

🎯 "ONCE IN A BLUE MOON" - REPETICIÓN:
Este idiom apareció antes en el Nivel 87.

¿Por qué repetir? Porque es MUY común y merece refuerzo.

"Blue moon" astronómicamente = segunda luna llena en un mes (cada 2-3 años)

Por eso "once in a blue moon" = MUY raramente

⚠️ "GIVE BENEFIT OF THE DOUBT" - ESTRUCTURA:
Estructura correcta: "Give [someone] the benefit of the doubt"

✅ "Give HIM the benefit of the doubt"
✅ "Give HER the benefit of the doubt"
✅ "Give ME the benefit of the doubt"

❌ NO: "Give the benefit of the doubt" (falta el objeto)

Significa: Asumir inocencia/buenas intenciones cuando no estás seguro.

💡 "SEE EYE TO EYE" - NEGATIVO MÁS COMÚN:
Se usa más en NEGATIVO que positivo:

Más común: "We don't see eye to eye" ❌
Menos común: "We see eye to eye" ✅

¿Por qué? Porque mencionamos desacuerdos más que acuerdos.

Ejemplos:
"My boss and I don't see eye to eye on this."
"We never see eye to eye on politics."
"They rarely see eye to eye."

