💡 "ADD INSULT TO INJURY" - USO:
Se usa cuando una mala situación empeora:

"I lost my job (injury), and to add insult to injury, my car broke down the same day (insult)!"

Estructura: [problema 1], and to add insult to injury, [problema 2]

🎯 "KILL TWO BIRDS WITH ONE STONE" - NOTA CULTURAL:
⚠️ Algunos consideran esta expresión violenta.
Alternativa moderna: "Feed two birds with one scone"
(Alimentar dos pájaros con un panecillo)

Pero "kill two birds" sigue siendo la versión más común.

⚠️ "EVERY CLOUD HAS A SILVER LINING" - ORIGEN:
De John Milton (1634): "Was I deceived, or did a sable cloud turn forth her silver lining on the night?"

Significa: Incluso las nubes oscuras (problemas) tienen un borde plateado (algo bueno).

Similar a "A blessing in disguise" pero más general.

💡 "NO PAIN, NO GAIN" - CONTEXTOS:
Originalmente del fitness/ejercicio, pero ahora se usa para TODO:

- Ejercicio: "This workout hurts! No pain, no gain!"
- Estudios: "Study harder! No pain, no gain!"
- Negocios: "We need to invest more. No pain, no gain!"
- Vida: "Success requires sacrifice. No pain, no gain!"

🎯 "THE BEST OF BOTH WORLDS" - SITUACIONES:
Se usa cuando puedes disfrutar ventajas de DOS situaciones normalmente incompatibles:

✅ Trabajo remoto: oficina Y casa
✅ Carro híbrido: potencia Y eficiencia
✅ Vivir cerca ciudad Y playa
✅ Comida saludable Y deliciosa

⚠️ DIFERENCIA SUTIL:
"Can't judge a book by its cover" vs "Every cloud has a silver lining"

📚 Book by cover = No juzgar ANTES (apariencias)
☁️ Cloud/silver lining = Ser optimista DESPUÉS (problemas)

Ejemplo:
"Don't judge him by his appearance" (book by cover)
"I got fired, but every cloud has a silver lining - now I can pursue my dream!" (silver lining)

💡 USO EN MOTIVACIÓN:
Estos tres se usan CONSTANTEMENTE para motivar:

1. "Practice makes perfect" - Para animar a seguir intentando
2. "No pain, no gain" - Para empujar a esforzarse más
3. "Every cloud has a silver lining" - Para dar esperanza

