⚠️ ORIGEN - "THE LAST STRAW":
Expresión completa: "The last straw that broke the camel's back"
(La última paja que rompió la espalda del camello)

Imagina: un camello cargando paja. Puede cargar mucho, pero eventualmente una última paja pequeña rompe su espalda.

Ahora = el problema final que hace que alguien explote o renuncie.

💡 "A BLESSING IN DISGUISE" - USO:
Solo se usa para eventos PASADOS, nunca futuros:

✅ Correcto: "Losing that job was a blessing in disguise"
❌ Incorrecto: "This will be a blessing in disguise"

Porque solo sabes que fue una "bendición" DESPUÉS de ver los resultados positivos.

🎯 "CALL IT A DAY" - VARIACIONES:
- Call it a day = terminar por HOY
- Call it a night = terminar por esta NOCHE  
- Call it quits = terminar PERMANENTEMENTE

Ejemplos:
"Let's call it a day" (son las 5pm, terminemos el trabajo)
"Let's call it a night" (es medianoche, terminemos la fiesta)
"Let's call it quits" (terminemos esta relación/proyecto para siempre)

⚠️ "ON THE SAME PAGE" - CONTEXTO:
MUY común en reuniones de trabajo/negocios:

"Before we start, let's make sure everyone is on the same page."
"Are we on the same page about the timeline?"
"I want to get everyone on the same page regarding expectations."

Significa: asegurar que todos tengan el mismo entendimiento/información.

💡 "GET OUT OF HAND" - PROGRESIÓN:
under control → getting out of hand → out of control

1. "Everything is under control" ✅
2. "Things are getting out of hand" ⚠️
3. "Everything is out of control" ❌

🎯 "GIVE THE COLD SHOULDER" - ORIGEN:
En la época medieval, cuando alguien no era bienvenido, el anfitrión le servía "cold shoulder of mutton" (hombro frío de cordero - sobras frías) en vez de comida caliente fresca.

Ahora = tratar a alguien con frialdad, ignorarlo.

⚠️ "GET IT OFF YOUR CHEST" - SIGNIFICADO PROFUNDO:
No es solo "decir algo", es más específico:
- Algo que te ha estado molestando ✅
- Un secreto o confesión ✅
- Algo que necesitas decir para sentirte mejor ✅

No se usa para información casual ❌

Ejemplo:
✅ "I need to get this off my chest: I broke your vase last year"
❌ "Let me get off my chest what I had for lunch" (incorrecto)

