Moraleja: Si das falsas alarmas, nadie te creerá en emergencias reales.

💡 "A DIME A DOZEN" - CONTEXTO AMERICANO:
"Dime" = moneda de 10 centavos (US)
Si algo cuesta 10 centavos por docena = BARATÍSIMO/COMÚN

Ahora = tan común que no tiene valor especial.

⚠️ Solo estadounidense. En UK se dice: "Two a penny"

Similar en español: "Del montón" / "Como arena en el mar"

🎯 "BURN THE MIDNIGHT OIL" - ORIGEN HISTÓRICO:
Antes de electricidad, la gente usaba lámparas de aceite.
Trabajar tan tarde que quemabas aceite después de medianoche = trabajar MUY tarde.

Ahora = trabajar hasta tarde/trasnochar estudiando o trabajando.

Muy común en:
- Estudiantes antes de exámenes 📚
- Trabajadores con deadlines ⏰
- Emprendedores 💼

⚠️ "BEAT A DEAD HORSE" - VISUALIZACIÓN:
