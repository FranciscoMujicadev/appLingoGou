⚠️ ORIGEN - "BITE THE BULLET":
De cirugías de guerra del siglo XIX.
Sin anestesia, los soldados mordían una bala de plomo durante operaciones para soportar el dolor.

Ahora = hacer algo difícil/doloroso pero necesario.

💡 "A PENNY FOR YOUR THOUGHTS" - USO MODERNO:
Frase ANTIGUA (de 1500s), pero aún muy común.
Se usa cuando alguien está:
- Callado y pensativo 🤔
- Distraído 😶
- Preocupado 😟

Es una forma AMABLE de preguntar: "¿Qué pasa?"

Respuesta común: "Oh, nothing. Just thinking."

🎯 "BACK TO THE DRAWING BOARD" - CONTEXTOS:
Muy común en:
- Proyectos que fallan 📊
- Diseños que no funcionan 🎨
- Planes que se cancelan 📋
- Estrategias que no sirven 💼

Siempre implica: empezar TODO de nuevo.

Similar a: "Back to square one" (de vuelta al inicio)

⚠️ "BREAK THE ICE" - ICEBREAKER:
Sustantivo: "icebreaker" = actividad para romper el hielo

Ejemplos:
"Let's do an icebreaker game!" (juego para conocerse)
"Tell us a fun fact as an icebreaker." (romper tensión)

Muy común en:
- Primeras reuniones de equipo
- Eventos de networking
- Primeras clases/cursos
- Fiestas con desconocidos

💡 "BY THE SKIN OF YOUR TEETH" - ORIGEN BÍBLICO:
Del Libro de Job (Biblia): "I am escaped with the skin of my teeth"

Dato curioso: Los dientes NO tienen piel.
Por eso significa "por muy muy poco" - casi imposible.

Sinónimos:
- "Just barely" (apenas)
- "By a hair" (por un pelo)
- "Narrowly" (por poco)

🎯 "CRY OVER SPILLED MILK" - FORMA COMPLETA:
Frase completa: "No use crying over spilled milk"
Forma corta: "Don't cry over spilled milk"

Se usa para decir: lo que pasó, pasó. No vale la pena lamentarse.

Similar a: "What's done is done"

⚠️ "CUT CORNERS" - CONNOTACIÓN NEGATIVA:
Siempre tiene connotación NEGATIVA:

❌ "They cut corners on safety" (peligroso)
❌ "Don't cut corners on quality" (mal trabajo)
❌ "The builder cut corners" (construcción defectuosa)

NO confundir con:
✅ "Take a shortcut" (atajo físico) = neutral/positivo
✅ "Work efficiently" (eficiencia) = positivo

